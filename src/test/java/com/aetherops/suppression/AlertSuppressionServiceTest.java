package com.aetherops.suppression;

import com.aetherops.common.exception.ResourceNotFoundException;
import com.aetherops.ratelimit.SlidingWindowRateLimiterService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.extension.ExtendWith;
import org.mockito.InjectMocks;
import org.mockito.Mock;
import org.mockito.junit.jupiter.MockitoExtension;
import org.springframework.test.util.ReflectionTestUtils;

import java.time.Instant;
import java.util.List;
import java.util.Optional;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.ArgumentMatchers.anyInt;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

@ExtendWith(MockitoExtension.class)
class AlertSuppressionServiceTest {

    @Mock private AlertSuppressionRuleRepository ruleRepository;
    @Mock private SlidingWindowRateLimiterService slidingWindowRateLimiter;

    @InjectMocks
    private AlertSuppressionService suppressionService;

    private final UUID tenantId = UUID.randomUUID();

    @BeforeEach
    void setUp() {
        // @Value isn't processed outside a Spring context — set the same defaults the
        // production @Value("...:10")/@Value("...:30") annotations resolve to at runtime.
        ReflectionTestUtils.setField(suppressionService, "noisyAlertThreshold", 10);
        ReflectionTestUtils.setField(suppressionService, "autoMuteMinutes", 30);
    }

    private AlertSuppressionRule rule(String serviceId, String alertName, Instant mutedUntil, boolean auto) {
        return AlertSuppressionRule.builder()
            .id(UUID.randomUUID()).tenantId(tenantId)
            .serviceId(serviceId).alertName(alertName).mutedUntil(mutedUntil).autoGenerated(auto)
            .createdAt(Instant.now())
            .build();
    }

    @Test
    void mute_savesRuleAndReturnsResponse() {
        when(ruleRepository.save(any())).thenAnswer(i -> i.getArgument(0));
        MuteAlertRequest request = new MuteAlertRequest("db-svc", "high_cpu", null, "known flaky check", "alice");

        AlertSuppressionRuleResponse response = suppressionService.mute(tenantId, request);

        assertThat(response.getTenantId()).isEqualTo(tenantId);
        assertThat(response.getServiceId()).isEqualTo("db-svc");
        assertThat(response.isAutoGenerated()).isFalse();
    }

    @Test
    void unmute_existingRule_deletesIt() {
        AlertSuppressionRule existing = rule("db-svc", null, null, false);
        when(ruleRepository.findById(existing.getId())).thenReturn(Optional.of(existing));

        suppressionService.unmute(tenantId, existing.getId());

        verify(ruleRepository).delete(existing);
    }

    @Test
    void unmute_ruleBelongsToDifferentTenant_throwsResourceNotFound() {
        AlertSuppressionRule existing = rule("db-svc", null, null, false);
        existing.setTenantId(UUID.randomUUID());
        when(ruleRepository.findById(existing.getId())).thenReturn(Optional.of(existing));

        assertThatThrownBy(() -> suppressionService.unmute(tenantId, existing.getId()))
            .isInstanceOf(ResourceNotFoundException.class);
    }

    @Test
    void unmute_unknownRule_throwsResourceNotFound() {
        UUID ruleId = UUID.randomUUID();
        when(ruleRepository.findById(ruleId)).thenReturn(Optional.empty());

        assertThatThrownBy(() -> suppressionService.unmute(tenantId, ruleId))
            .isInstanceOf(ResourceNotFoundException.class);
    }

    @Test
    void listActive_excludesExpiredRules() {
        AlertSuppressionRule active = rule("db-svc", null, Instant.now().plusSeconds(3600), false);
        AlertSuppressionRule expired = rule("api-svc", null, Instant.now().minusSeconds(3600), false);
        AlertSuppressionRule indefinite = rule("web-svc", null, null, false);
        when(ruleRepository.findByTenantId(tenantId)).thenReturn(List.of(active, expired, indefinite));

        List<AlertSuppressionRuleResponse> result = suppressionService.listActive(tenantId);

        assertThat(result).extracting(AlertSuppressionRuleResponse::getServiceId)
            .containsExactlyInAnyOrder("db-svc", "web-svc");
    }

    @Test
    void isSuppressed_wildcardServiceRule_matchesAnyService() {
        when(ruleRepository.findByTenantId(tenantId)).thenReturn(List.of(rule(null, null, null, false)));

        assertThat(suppressionService.isSuppressed(tenantId, "any-svc", "any_alert")).isTrue();
    }

    @Test
    void isSuppressed_serviceSpecificRule_doesNotMatchOtherService() {
        when(ruleRepository.findByTenantId(tenantId)).thenReturn(List.of(rule("db-svc", null, null, false)));

        assertThat(suppressionService.isSuppressed(tenantId, "api-svc", "any_alert")).isFalse();
    }

    @Test
    void isSuppressed_noRules_returnsFalse() {
        when(ruleRepository.findByTenantId(tenantId)).thenReturn(List.of());

        assertThat(suppressionService.isSuppressed(tenantId, "db-svc", "high_cpu")).isFalse();
    }

    @Test
    void shouldSuppress_existingRuleMatches_returnsTrueWithoutCheckingOccurrenceCount() {
        when(ruleRepository.findByTenantId(tenantId)).thenReturn(List.of(rule("db-svc", null, null, false)));

        assertThat(suppressionService.shouldSuppress(tenantId, "db-svc", "high_cpu")).isTrue();
    }

    @Test
    void shouldSuppress_belowThreshold_returnsFalse() {
        when(ruleRepository.findByTenantId(tenantId)).thenReturn(List.of());
        when(slidingWindowRateLimiter.currentCount(any(), anyInt())).thenReturn(3L);

        assertThat(suppressionService.shouldSuppress(tenantId, "db-svc", "high_cpu")).isFalse();
    }

    @Test
    void shouldSuppress_crossesThreshold_autoMutesAndReturnsTrue() {
        when(ruleRepository.findByTenantId(tenantId)).thenReturn(List.of());
        when(slidingWindowRateLimiter.currentCount(any(), anyInt())).thenReturn(10L);
        when(ruleRepository.save(any())).thenAnswer(i -> i.getArgument(0));

        boolean result = suppressionService.shouldSuppress(tenantId, "db-svc", "high_cpu");

        assertThat(result).isTrue();
        org.mockito.ArgumentCaptor<AlertSuppressionRule> captor = org.mockito.ArgumentCaptor.forClass(AlertSuppressionRule.class);
        verify(ruleRepository).save(captor.capture());
        assertThat(captor.getValue().isAutoGenerated()).isTrue();
        assertThat(captor.getValue().getMutedUntil()).isAfter(Instant.now());
    }

    @Test
    void shouldSuppress_customThreshold_respected() {
        ReflectionTestUtils.setField(suppressionService, "noisyAlertThreshold", 2);
        when(ruleRepository.findByTenantId(tenantId)).thenReturn(List.of());
        when(slidingWindowRateLimiter.currentCount(any(), anyInt())).thenReturn(2L);
        when(ruleRepository.save(any())).thenAnswer(i -> i.getArgument(0));

        assertThat(suppressionService.shouldSuppress(tenantId, "db-svc", "high_cpu")).isTrue();
    }
}
