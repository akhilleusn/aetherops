-- Matches OnCallRotation (table: oncall_rotation, Long id/tenant_id, per existing on-call model)
CREATE TABLE oncall_rotation (
    id                 BIGINT      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id          BIGINT      NOT NULL,
    service_id         VARCHAR(100) NOT NULL,
    rotation_name      VARCHAR(150) NOT NULL,
    rotation_start_at  TIMESTAMPTZ NOT NULL,
    shift_length_hours INTEGER     NOT NULL
);

-- @ElementCollection default table name for OnCallRotation.participants
CREATE TABLE oncall_rotation_participants (
    oncall_rotation_id BIGINT      NOT NULL REFERENCES oncall_rotation(id) ON DELETE CASCADE,
    participant_order  INTEGER     NOT NULL,
    participants       VARCHAR(20) NOT NULL CHECK (participants ~ '^\+[1-9]\d{1,14}$'),
    PRIMARY KEY (oncall_rotation_id, participant_order)
);

CREATE INDEX idx_oncall_rotation_tenant_service ON oncall_rotation (tenant_id, service_id);
