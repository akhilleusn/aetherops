package com.aetherops.suppression;

import com.aetherops.common.exception.ResourceNotFoundException;
import com.aetherops.ratelimit.SlidingWindowRateLimiterService;
import lombok.RequiredArgsConstructor;
import lombok.extern.slf4j.Slf4j;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Service;
import org.springframework.transaction.annotation.Transactional;

import java.time.Instant;
import java.util.List;
import java.util.UUID;

/**
 * Manual mutes (a human suppressing a known-noisy alert) plus automatic noisy-alert
 * detection, backed by the same Redis sliding-window counter the API rate limiter uses
 * (see {@code com.aetherops.ratelimit.IpRateLimitFilter}) — reused here for "how many
 * times has this exact alert fired recently", which is the same shape of problem.
 */
@Service
@RequiredArgsConstructor
@Slf4j
public class AlertSuppressionService {

    private static final int OCCURRENCE_WINDOW_SECONDS = 300;

    private final AlertSuppressionRuleRepository ruleRepository;
    private final SlidingWindowRateLimiterService slidingWindowRateLimiter;

    @Value("${app.suppression.noisy-alert-threshold:10}")
    private int noisyAlertThreshold;

    @Value("${app.suppression.auto-mute-minutes:30}")
    private int autoMuteMinutes;

    @Transactional
    public AlertSuppressionRuleResponse mute(UUID tenantId, MuteAlertRequest request) {
        AlertSuppressionRule rule = AlertSuppressionRule.builder()
            .tenantId(tenantId)
            .serviceId(request.getServiceId())
            .alertName(request.getAlertName())
            .mutedUntil(request.getMutedUntil())
            .reason(request.getReason())
            .createdBy(request.getCreatedBy())
            .autoGenerated(false)
            .build();

        AlertSuppressionRule saved = ruleRepository.save(rule);
        log.info("Muted alerts tenantId={} serviceId={} alertName={} until={}",
            tenantId, request.getServiceId(), request.getAlertName(), request.getMutedUntil());
        return toResponse(saved);
    }

    @Transactional
    public void unmute(UUID tenantId, UUID ruleId) {
        AlertSuppressionRule rule = ruleRepository.findById(ruleId)
            .filter(r -> r.getTenantId().equals(tenantId))
            .orElseThrow(() -> new ResourceNotFoundException("No suppression rule found: " + ruleId));
        ruleRepository.delete(rule);
        log.info("Unmuted alert suppression rule id={} tenantId={}", ruleId, tenantId);
    }

    @Transactional(readOnly = true)
    public List<AlertSuppressionRuleResponse> listActive(UUID tenantId) {
        Instant now = Instant.now();
        return ruleRepository.findByTenantId(tenantId).stream()
            .filter(r -> r.isActive(now))
            .map(this::toResponse)
            .toList();
    }

    /**
     * Records this occurrence and returns whether it should be dropped: either an existing
     * manual/auto rule already covers it, or it just tripped the noisy-alert threshold and
     * got auto-muted on the spot (so the occurrence that crossed the threshold is itself
     * suppressed too, rather than needing one more flood cycle before the mute takes effect).
     */
    @Transactional
    public boolean shouldSuppress(UUID tenantId, String serviceId, String alertName) {
        if (isSuppressed(tenantId, serviceId, alertName)) {
            return true;
        }

        String key = "alert-suppress:" + tenantId + ":" + serviceId + ":" + alertName;
        long count = slidingWindowRateLimiter.currentCount(key, OCCURRENCE_WINDOW_SECONDS);

        if (count >= noisyAlertThreshold) {
            autoMute(tenantId, serviceId, alertName, count);
            return true;
        }

        return false;
    }

    @Transactional(readOnly = true)
    public boolean isSuppressed(UUID tenantId, String serviceId, String alertName) {
        Instant now = Instant.now();
        return ruleRepository.findByTenantId(tenantId).stream()
            .filter(r -> r.isActive(now))
            .anyMatch(r -> r.matches(serviceId, alertName));
    }

    private void autoMute(UUID tenantId, String serviceId, String alertName, long occurrenceCount) {
        AlertSuppressionRule rule = AlertSuppressionRule.builder()
            .tenantId(tenantId)
            .serviceId(serviceId)
            .alertName(alertName)
            .mutedUntil(Instant.now().plusSeconds(autoMuteMinutes * 60L))
            .reason("Auto-suppressed: " + occurrenceCount + " occurrences in " + (OCCURRENCE_WINDOW_SECONDS / 60) + " minutes")
            .autoGenerated(true)
            .build();
        ruleRepository.save(rule);
        log.warn("Auto-suppressed noisy alert tenantId={} serviceId={} alertName={} occurrenceCount={} muteMinutes={}",
            tenantId, serviceId, alertName, occurrenceCount, autoMuteMinutes);
    }

    private AlertSuppressionRuleResponse toResponse(AlertSuppressionRule rule) {
        return AlertSuppressionRuleResponse.builder()
            .id(rule.getId())
            .tenantId(rule.getTenantId())
            .serviceId(rule.getServiceId())
            .alertName(rule.getAlertName())
            .mutedUntil(rule.getMutedUntil())
            .reason(rule.getReason())
            .createdBy(rule.getCreatedBy())
            .autoGenerated(rule.isAutoGenerated())
            .createdAt(rule.getCreatedAt())
            .build();
    }
}
