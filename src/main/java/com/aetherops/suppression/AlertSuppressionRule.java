package com.aetherops.suppression;

import jakarta.persistence.*;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import org.hibernate.annotations.CreationTimestamp;

import java.time.Instant;
import java.util.UUID;

@Entity
@Table(name = "alert_suppression_rules")
@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class AlertSuppressionRule {

    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    private UUID id;

    @Column(name = "tenant_id", nullable = false)
    private UUID tenantId;

    /** Null matches every service for this tenant. */
    @Column(name = "service_id", length = 100)
    private String serviceId;

    /** Null matches every alert name for the matched service. */
    @Column(name = "alert_name", length = 255)
    private String alertName;

    /** Null means muted indefinitely, until explicitly unmuted. */
    @Column(name = "muted_until")
    private Instant mutedUntil;

    @Column(length = 500)
    private String reason;

    @Column(name = "created_by", length = 255)
    private String createdBy;

    @Column(name = "auto_generated", nullable = false)
    private boolean autoGenerated;

    @CreationTimestamp
    @Column(name = "created_at", nullable = false, updatable = false)
    private Instant createdAt;

    public boolean isActive(Instant now) {
        return mutedUntil == null || mutedUntil.isAfter(now);
    }

    public boolean matches(String candidateServiceId, String candidateAlertName) {
        boolean serviceMatches = serviceId == null || serviceId.equals(candidateServiceId);
        boolean alertMatches = alertName == null || alertName.equals(candidateAlertName);
        return serviceMatches && alertMatches;
    }
}
